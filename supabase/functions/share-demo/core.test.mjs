import assert from 'node:assert/strict';
import { canPatientDecide, canRequestSession, compactOpaqueToken, normalizeOpaqueToken, numericShareCodeFromUint32, validOpaqueToken, validUuid } from './core.ts';

assert.equal(validUuid('00000000-0000-4000-8000-000000000001'), true);
assert.equal(validUuid('not-a-uuid'), false);
assert.equal(validOpaqueToken('00000000-0000-4000-8000-000000000001'), true);
assert.equal(normalizeOpaqueToken('00000000-0000-4000-8000-ABCDEFABCDEF'), '00000000-0000-4000-8000-abcdefabcdef');
assert.equal(validOpaqueToken('aB-cD_12'), true);
assert.equal(normalizeOpaqueToken('aB-cD_12'), 'aB-cD_12');
assert.equal(compactOpaqueToken('01234567-89ab-4cde-8f01-23456789abcd'), 'ASNFZ4mr');
assert.equal(numericShareCodeFromUint32(7), '00000007');
assert.equal(numericShareCodeFromUint32(12345678), '12345678');
assert.equal(numericShareCodeFromUint32(4_200_000_000), null, 'out-of-range values are rejected to avoid modulo bias');
assert.equal(normalizeOpaqueToken('not-a-token'), null);
assert.equal(canRequestSession('pending', '2026-07-18T00:10:00Z', Date.parse('2026-07-18T00:00:00Z')), true);
assert.equal(canRequestSession('approved', '2026-07-18T00:10:00Z', Date.parse('2026-07-18T00:00:00Z')), false);
assert.equal(canPatientDecide('requested', '2026-07-18T00:10:00Z', Date.parse('2026-07-18T00:00:00Z')), true);
assert.equal(canPatientDecide('pending', '2026-07-18T00:10:00Z', Date.parse('2026-07-18T00:00:00Z')), false);
assert.equal(canRequestSession('revoked', '2026-07-18T00:10:00Z', Date.parse('2026-07-18T00:00:00Z')), false);
assert.equal(canRequestSession('pending', '2026-07-17T23:59:00Z', Date.parse('2026-07-18T00:00:00Z')), false);
console.log('share demo security tests passed');
